#!/bin/bash
# Package Student Agenda as a Chrome extension (side panel).
#
#   ./build.sh                                   bundled announcements only
#   NEWS_URL=https://example.org/data/announcements.json ./build.sh
#                                                 live announcements from the hosted web app
#
# Output: dist/extension/ (Load unpacked) and dist/student-agenda-extension.zip
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
OUT="$SRC/dist/extension"
NEWS_URL="${NEWS_URL:-}"

rm -rf "$SRC/dist"
mkdir -p "$OUT/data" "$OUT/icons"

# Shared app files — the same ones the web app serves.
cp "$SRC/index.html" "$SRC/app.js" "$SRC/styles.css" "$OUT/"
cp "$SRC/data/calendar.js" "$SRC/data/config.js" "$SRC/data/announcements.json" "$OUT/data/"
cp "$SRC/icons/icon.svg" "$SRC/icons/bomber-bob.png" "$OUT/icons/"

# Extension-only files.
cp "$SRC/extension/manifest.json" "$SRC/extension/background.js" "$OUT/"
for size in 16 32 48 128; do
  sips -z "$size" "$size" "$SRC/icons/icon-512.png" --out "$OUT/icons/ext-$size.png" >/dev/null
done

# The extension has no web manifest or service worker; drop those tags.
sed -i '' -e '/rel="manifest"/d' -e '/apple-/d' "$OUT/index.html"

if [ -n "$NEWS_URL" ]; then
  python3 - "$OUT" "$NEWS_URL" <<'PY'
import json, sys
from urllib.parse import urlsplit
out, url = sys.argv[1], sys.argv[2]
parts = urlsplit(url)
if parts.scheme != "https":
    sys.exit("NEWS_URL must be https")
with open(f"{out}/data/config.js", "w") as f:
    f.write("// Generated by build.sh for the Chrome extension.\n")
    f.write(f"const AgendaConfig = {{\n  newsUrl: {json.dumps(url)}\n}};\n")
m = json.load(open(f"{out}/manifest.json"))
m["host_permissions"] = [f"{parts.scheme}://{parts.netloc}/*"]
json.dump(m, open(f"{out}/manifest.json", "w"), indent=2, ensure_ascii=False)
PY
  echo "Announcements: $NEWS_URL"
else
  echo "Announcements: bundled copy (set NEWS_URL for live posts)"
fi

(cd "$OUT" && zip -qr "$SRC/dist/student-agenda-extension.zip" .)

echo "Built: $OUT"
echo "Zip:   $SRC/dist/student-agenda-extension.zip"
